// l'etape a dire, ou null (impression normale, rien, ou etape inconnue)
export function stageLabel(st) {
  const n = st?.print_stage;
  if (n == null || n === 0 || n === -1 || n === 255) return null;
  return STAGES[n] || null;
}
// une etape de pause (une raison a lire) plutot qu'une etape de preparation
export const stageIsPause = st => /^Pause/.test(stageLabel(st) || "");
